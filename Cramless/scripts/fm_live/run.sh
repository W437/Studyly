#!/bin/bash
# Runs the app's own on-device AI code against the real Foundation Models model on this Mac (Apple silicon with Apple
# Intelligence on; the simulator has no model). It compiles the app's AI sources (models, contract, outcomes,
# on-device jobs, offline rules, grounding check) with two small stubs into a command-line program and asks the model
# to write questions from the sample page, grade three answers and answer four tutor questions, printing what the app
# would keep. Change a prompt, a schema or a mapping, then run this again: the small model reacts to wording.
#
#   scripts/fm_live/run.sh            (about a minute; the output also goes to build/fm_live/last-run.txt)
set -eu
cd "$(dirname "$0")/../.."
out=build/fm_live
rm -rf "$out/src"; mkdir -p "$out/src"
cp Cramless/Model/ModelTypes.swift Cramless/AI/RelayContract.swift Cramless/AI/AIOutcomes.swift \
   Cramless/AI/GroundingCheck.swift Cramless/AI/OnDevice/*.swift Cramless/AI/Local/*.swift "$out/src/"
cp scripts/fm_live/main.swift "$out/src/main.swift"
python3 - "$out/src/HarnessStubs.swift" <<'PY'
import re, sys
src = open("Cramless/DesignSystem/Components/Highlighter.swift").read()
struct = re.search(r"struct HighlightMark: Hashable, Sendable \{.*?\n\}\n", src, re.S).group(0)
ext = re.search(r"extension HighlightMark \{.*\n\}\n?$", src, re.S).group(0)
open(sys.argv[1], "w").write("""import Foundation
// Generated by scripts/fm_live/run.sh: the app-only types the AI sources reference. HighlightMark is copied from
// DesignSystem/Components/Highlighter.swift; the rest are minimal stand-ins.
""" + struct + "\n" + ext + """
enum ConsentReason: Hashable, Sendable { case cloudAI(feature: String); case photos }
enum PaywallContext: Hashable, Sendable { case onboarding(planLine: String); case feature(String); case settings }
enum AppSheet: Hashable, Sendable { case consent(ConsentReason); case paywall(PaywallContext) }
enum ItemFactory {
    static func timestamp(_ seconds: Double) -> String {
        let s = Int(seconds.rounded(.down))
        return String(format: "%02d:%02d", s / 60, s % 60)
    }
    static func shortTitle(_ title: String) -> String {
        if let colon = title.firstIndex(of: ":") { return String(title[..<colon]) }
        return title
    }
}
""")
PY
swiftc -O -target arm64-apple-macos26.0 "$out"/src/*.swift -o "$out/fm_live"
"$out/fm_live" Cramless/Resources/Sample/sample-mitosis-p87.json supabase/functions/_shared/fixtures/generate.json \
  | tee "$out/last-run.txt"
