#!/usr/bin/env python3
"""The four alternate app icons (Night, Ember, Gold, Aurora) and the picker's previews, made from the main icon.

Cap is cut out of AppIcon.png (a flat vector on one blue, so the cut is exact: each edge pixel's share of Cap is worked out
against that blue), set on four new skies drawn here, and written into the asset catalog. Nothing is generated by a model
and nothing is spent: run it again and it writes the same files.

    python3 scripts/make_alt_icons.py            # writes the four icon sets and the five preview sets
    python3 scripts/make_alt_icons.py --sheet    # also writes build/icons/sheet.png to look at

Needs Pillow and NumPy. NumPy 2.2 on Python 3.14 can change an array in place under `~a`, `a | b` and `a - b`, so every
array operation below is a ufunc call (np.subtract, np.logical_not, …), never an operator.
"""
import argparse
import json
import os
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "Cramless", "Resources", "Assets.xcassets")
SOURCE = os.path.join(CATALOG, "AppIcon.appiconset", "AppIcon.png")
SIZE = 1024
F32 = np.float32


def rgb(*values):
    return np.array(values, F32)


# MARK: cutting Cap out

def spread(colour_in, seeds, reach):
    """Cap's colour carried outward from the seed pixels, one ring at a time, `reach` rings at most."""
    colour = np.where(seeds[..., None], colour_in, 0).astype(F32)
    have = seeds.copy()
    for _ in range(reach):
        weighted = np.multiply(colour, have[..., None].astype(F32))
        total = np.zeros_like(colour)
        count = np.zeros(seeds.shape, F32)
        solid = have.astype(F32)
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                if dy or dx:
                    np.add(total, np.roll(np.roll(weighted, dy, 0), dx, 1), out=total)
                    np.add(count, np.roll(np.roll(solid, dy, 0), dx, 1), out=count)
        new = np.logical_and(np.logical_not(have), np.greater(count, 0))
        colour[new] = np.divide(total[new], count[new][:, None])
        have = np.logical_or(have, new)
    return colour, have


def erode(mask, rings):
    out = mask.copy()
    for _ in range(rings):
        shrunk = out.copy()
        for dy in (-1, 0, 1):
            for dx in (-1, 0, 1):
                np.logical_and(shrunk, np.roll(np.roll(out, dy, 0), dx, 1), out=shrunk)
        out = shrunk
    return out


def cut_out(icon):
    """(colour, alpha): Cap's own colours, and how much of each pixel is Cap."""
    px = icon.astype(F32)
    bg = px[5, 5]
    delta = np.subtract(px, bg)
    dist = np.sqrt(np.multiply(delta, delta).sum(axis=2))
    core = erode(np.greater(dist, 40), 2)
    colour, have = spread(px, core, 5)
    edge = np.logical_and(np.logical_not(core), have)
    away = np.subtract(colour, bg)
    # A pixel is part Cap, part blue: how far along the line from the blue to Cap's colour it lies.
    num = np.multiply(delta, away).sum(axis=2)
    den = np.maximum(np.multiply(away, away).sum(axis=2), 1.0)
    share = np.clip(np.divide(num, den), 0, 1)
    alpha = np.where(core, 1.0, np.where(edge, share, 0.0)).astype(F32)
    colour = np.where(core[..., None], px, colour)
    return colour, alpha


# MARK: painting

def blur(array, radius):
    """A blurred copy of a float image (h, w), values 0..1."""
    im = Image.fromarray(np.clip(array * 255, 0, 255).astype(np.uint8), "L").filter(ImageFilter.GaussianBlur(radius))
    return np.divide(np.asarray(im).astype(F32), 255.0)


def flat(colour):
    return np.ones((SIZE, SIZE, 3), F32) * rgb(*colour)


def vertical(top, bottom, ease=1.0):
    t = np.power(np.linspace(0, 1, SIZE, dtype=F32), ease)
    column = np.add(np.multiply(rgb(*top)[None, :], np.subtract(1.0, t)[:, None]), np.multiply(rgb(*bottom)[None, :], t[:, None]))
    return np.repeat(column[:, None, :], SIZE, axis=1)


GRID = np.mgrid[0:SIZE, 0:SIZE].astype(F32)  # ys, xs


def glow(canvas, centre, radius, colour, strength):
    """A soft round light added to the canvas, falling to nothing at `radius`, easing off as the canvas brightens."""
    ys, xs = GRID
    dx, dy = np.subtract(xs, centre[0]), np.subtract(ys, centre[1])
    d = np.divide(np.sqrt(np.add(np.multiply(dx, dx), np.multiply(dy, dy))), radius)
    falloff = np.power(np.clip(np.subtract(1.0, d), 0, 1), 2)
    light = np.multiply(np.multiply(falloff[..., None], rgb(*colour)[None, None, :]), strength)
    room = np.subtract(1.0, np.divide(canvas, 330.0))
    return np.add(canvas, np.multiply(light, room))


def over(canvas, layer, alpha):
    a = alpha[..., None]
    return np.add(np.multiply(canvas, np.subtract(1.0, a)), np.multiply(layer, a))


def sparkle(draw, x, y, r, fill):
    """A four-point glint."""
    pts = [(x, y - r), (x + r * 0.18, y - r * 0.18), (x + r, y), (x + r * 0.18, y + r * 0.18),
           (x, y + r), (x - r * 0.18, y + r * 0.18), (x - r, y), (x - r * 0.18, y - r * 0.18)]
    draw.polygon(pts, fill=fill)


def glints(items, softness=0.6):
    layer = Image.new("L", (SIZE, SIZE), 0)
    draw = ImageDraw.Draw(layer)
    for (x, y, r, a) in items:
        sparkle(draw, x, y, r, a)
    return np.divide(np.asarray(layer.filter(ImageFilter.GaussianBlur(softness))).astype(F32), 255.0)


def dots(count, seed, area, radius, alpha):
    """Points of light: how much of each pixel they cover, 0..1."""
    rng = np.random.default_rng(seed)
    layer = Image.new("L", (SIZE, SIZE), 0)
    draw = ImageDraw.Draw(layer)
    for _ in range(count):
        x = rng.uniform(area[0], area[2])
        y = rng.uniform(area[1], area[3])
        r = rng.uniform(*radius)
        a = int(255 * rng.uniform(*alpha))
        draw.ellipse([x - r, y - r, x + r, y + r], fill=a)
    return np.divide(np.asarray(layer).astype(F32), 255.0)


# MARK: the four skies. Each returns the sky and how Cap sits on it.

def night():
    canvas = vertical((18, 22, 78), (62, 84, 176), ease=0.9)
    canvas = glow(canvas, (560, 560), 640, (120, 150, 255), 0.55)
    canvas = over(canvas, flat((255, 255, 255)), np.multiply(dots(70, 11, (0, 0, SIZE, 760), (1.6, 4.2), (0.35, 0.95)), 0.95))
    # A crescent moon, and a few glints.
    moon = Image.new("L", (SIZE, SIZE), 0)
    ImageDraw.Draw(moon).ellipse([800, 92, 932, 224], fill=255)
    bite = Image.new("L", (SIZE, SIZE), 0)
    ImageDraw.Draw(bite).ellipse([838, 78, 970, 210], fill=255)
    crescent = np.clip(np.subtract(np.asarray(moon).astype(F32), np.asarray(bite).astype(F32)), 0, 255)
    crescent = np.divide(np.asarray(Image.fromarray(crescent.astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2))).astype(F32), 255.0)
    canvas = glow(canvas, (866, 158), 190, (255, 240, 190), 0.30)
    canvas = over(canvas, flat((255, 244, 205)), crescent)
    canvas = over(canvas, flat((255, 255, 255)),
                  glints([(120, 150, 34, 255), (260, 330, 20, 200), (900, 430, 26, 230), (70, 560, 18, 180), (700, 90, 22, 220)]))
    return canvas, dict(shadow=(6, 8, 40), strength=0.45)


def ember():
    canvas = vertical((34, 8, 14), (120, 30, 18), ease=0.8)
    canvas = glow(canvas, (512, 1250), 1100, (255, 120, 36), 0.85)
    canvas = glow(canvas, (860, 260), 420, (255, 150, 60), 0.30)
    canvas = glow(canvas, (150, 700), 360, (255, 120, 40), 0.22)
    # Sparks rising, brighter and bigger near the fire, each with a glow.
    rng = np.random.default_rng(23)
    layer = Image.new("L", (SIZE, SIZE), 0)
    draw = ImageDraw.Draw(layer)
    for _ in range(46):
        x = rng.uniform(0, SIZE)
        height = rng.uniform(0, 1) ** 1.6
        y = SIZE - 40 - height * 940
        r = 2.0 + 7.0 * (1 - height) * rng.uniform(0.4, 1)
        draw.ellipse([x - r, y - r, x + r, y + r], fill=int(255 * (0.45 + 0.55 * (1 - height))))
    sparks = np.divide(np.asarray(layer).astype(F32), 255.0)
    canvas = over(canvas, flat((255, 150, 40)), np.clip(np.multiply(blur(sparks, 9), 0.85), 0, 1))
    canvas = over(canvas, flat((255, 226, 150)), sparks)
    return canvas, dict(shadow=(30, 4, 6), strength=0.70, rim=(255, 196, 120))


def gold():
    canvas = vertical((8, 18, 46), (30, 52, 108), ease=0.9)
    ys, xs = GRID
    centre = (560, 560)
    dx, dy = np.subtract(xs, centre[0]), np.subtract(ys, centre[1])
    angle = np.arctan2(dy, dx)
    rays = np.add(0.5, np.multiply(0.5, np.cos(np.multiply(angle, 12))))
    reach = np.clip(np.subtract(1.0, np.divide(np.sqrt(np.add(np.multiply(dx, dx), np.multiply(dy, dy))), 900)), 0, 1)
    canvas = np.add(canvas, np.multiply(np.multiply(rays, reach)[..., None], rgb(255, 214, 120) * 0.10))
    canvas = glow(canvas, centre, 700, (255, 206, 96), 0.62)
    canvas = over(canvas, flat((255, 244, 200)),
                  glints([(130, 170, 44, 255), (900, 210, 36, 255), (220, 760, 26, 210), (930, 700, 30, 230), (650, 44, 20, 200)], 0.7))
    return canvas, dict(shadow=(4, 10, 30), strength=0.45, gold=True)


def aurora():
    canvas = vertical((4, 12, 34), (12, 46, 78), ease=0.85)
    ys, xs = GRID
    ribbons = [((60, 255, 170), 250, 90, 0.9, 0.0), ((70, 220, 235), 400, 80, 0.8, 1.7), ((150, 100, 255), 560, 70, 0.7, 3.1)]
    for colour, base, thickness, strength, phase in ribbons:
        wave = np.add(base, np.add(np.multiply(120, np.sin(np.add(np.divide(xs, 150.0), phase))),
                                   np.multiply(60, np.sin(np.add(np.divide(xs, 61.0), phase * 2)))))
        off = np.subtract(ys, wave)
        band = np.exp(np.negative(np.square(np.divide(off, thickness))))
        # Folds hang down from the ribbon like curtains.
        fold = np.multiply(np.sin(np.add(np.divide(xs, 23.0), phase * 3)), np.sin(np.divide(xs, 71.0)))
        curtain = np.add(0.55, np.multiply(0.45, fold))
        hang = np.where(np.greater(off, 0), np.add(0.55, np.multiply(0.45, np.exp(np.negative(np.divide(off, 260.0))))), 1.0)
        layer = np.multiply(np.multiply(band, hang), np.add(0.7, np.multiply(0.3, curtain)))
        layer = np.divide(np.asarray(Image.fromarray(np.clip(layer * 255, 0, 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(14))).astype(F32), 255.0)
        canvas = np.add(canvas, np.multiply(layer[..., None], rgb(*colour) * strength * 0.9))
    canvas = np.clip(canvas, 0, 255)
    canvas = over(canvas, flat((255, 255, 255)), np.multiply(dots(60, 31, (0, 0, SIZE, 640), (1.4, 3.6), (0.3, 0.9)), 0.9))
    canvas = glow(canvas, (560, 600), 600, (80, 200, 220), 0.30)
    return canvas, dict(shadow=(2, 14, 28), strength=0.50, rim=(110, 230, 235))


# MARK: Cap on a sky

def goldify(colour):
    """Cap's fur and nose as gold; his navy cap, cream headphones and yellow tassel keep their colours."""
    out = colour.copy()
    r, g, b = (np.divide(colour[..., c], 255.0) for c in range(3))
    mx = np.maximum(np.maximum(r, g), b)
    mn = np.minimum(np.minimum(r, g), b)
    delta = np.subtract(mx, mn)
    safe = np.maximum(delta, 1e-6)
    sat = np.divide(delta, np.maximum(mx, 1e-6))
    hue = np.zeros_like(mx)
    from_r = np.logical_and(np.greater(delta, 1e-6), np.equal(mx, r))
    from_g = np.logical_and(np.logical_and(np.greater(delta, 1e-6), np.equal(mx, g)), np.logical_not(from_r))
    from_b = np.logical_and(np.logical_and(np.greater(delta, 1e-6), np.logical_not(from_r)), np.logical_not(from_g))
    hue[from_r] = np.mod(np.divide(np.subtract(g, b), safe), 6)[from_r]
    hue[from_g] = np.add(np.divide(np.subtract(b, r), safe), 2)[from_g]
    hue[from_b] = np.add(np.divide(np.subtract(r, g), safe), 4)[from_b]
    hue = np.multiply(hue, 60)
    fur = np.logical_and(np.logical_and(np.greater_equal(hue, 8), np.less_equal(hue, 40)),
                         np.logical_and(np.greater(sat, 0.45), np.greater(mx, 0.28)))
    # The fur's shading is kept: the lightest fur is warm gold, the shadows and strokes go to bronze. A soft light slides
    # across it from the top left, as on a statue.
    ys, xs = GRID
    sheen = np.add(0.88, np.multiply(0.24, np.clip(np.subtract(1.15, np.divide(np.add(xs, ys), 1500.0)), 0, 1)))
    t = np.clip(np.multiply(np.divide(np.subtract(mx, 0.28), 0.98), sheen), 0, 1)
    stops = [(0.0, (92, 54, 6)), (0.25, (150, 94, 12)), (0.55, (222, 160, 30)), (0.8, (250, 200, 66)), (1.0, (255, 232, 140))]
    ramp = np.zeros(colour.shape, F32)
    for c in range(3):
        ramp[..., c] = np.interp(t, [s[0] for s in stops], [s[1][c] for s in stops])
    out[fur] = ramp[fur]
    return out


def compose(make, cap_colour, cap_alpha):
    canvas, options = make()
    colour = goldify(cap_colour) if options.get("gold") else cap_colour
    # A soft shadow of Cap, to lift him off the sky.
    shadow = np.roll(np.multiply(blur(cap_alpha, 26), options["strength"]), 18, axis=0)
    canvas = over(canvas, flat(options["shadow"]), np.clip(shadow, 0, 1))
    if options.get("rim"):
        rim = np.multiply(np.clip(np.subtract(blur(cap_alpha, 6), cap_alpha), 0, 1), 0.9)
        canvas = over(canvas, flat(options["rim"]), rim)
    if options.get("gold"):
        # A gold edge of light around the whole of him, like a statue in a spotlight.
        rim = np.multiply(np.clip(np.subtract(blur(cap_alpha, 10), cap_alpha), 0, 1), 0.8)
        canvas = over(canvas, flat((255, 214, 110)), rim)
    canvas = over(canvas, colour, cap_alpha)
    return Image.fromarray(np.clip(canvas, 0, 255).astype(np.uint8), "RGB")


# MARK: writing the catalog

def write_json(path, value):
    with open(path, "w") as f:
        json.dump(value, f, indent=2)
        f.write("\n")


def write_icon_set(name, image):
    folder = os.path.join(CATALOG, f"AppIcon-{name}.appiconset")
    os.makedirs(folder, exist_ok=True)
    image.save(os.path.join(folder, f"AppIcon-{name}.png"))
    write_json(os.path.join(folder, "Contents.json"), {
        "images": [{"filename": f"AppIcon-{name}.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"}],
        "info": {"author": "xcode", "version": 1},
    })


def write_preview(name, image):
    folder = os.path.join(CATALOG, f"IconPreview-{name}.imageset")
    os.makedirs(folder, exist_ok=True)
    images = []
    for scale in (1, 2, 3):
        file = f"IconPreview-{name}{'' if scale == 1 else f'@{scale}x'}.png"
        image.resize((84 * scale, 84 * scale), Image.LANCZOS).save(os.path.join(folder, file))
        images.append({"filename": file, "idiom": "universal", "scale": f"{scale}x"})
    write_json(os.path.join(folder, "Contents.json"), {"images": images, "info": {"author": "xcode", "version": 1}})


def rounded(image, size, radius):
    tile = image.resize((size, size), Image.LANCZOS)
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, size - 1, size - 1], radius=radius, fill=255)
    return tile, mask


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--sheet", action="store_true", help="also write build/icons/sheet.png")
    args = parser.parse_args()

    icon = np.asarray(Image.open(SOURCE).convert("RGB"))
    colour, alpha = cut_out(icon)
    images = {"Standard": Image.open(SOURCE).convert("RGB")}
    for name, make in {"Night": night, "Ember": ember, "Gold": gold, "Aurora": aurora}.items():
        images[name] = compose(make, colour, alpha)
        write_icon_set(name, images[name])
    for name, image in images.items():
        write_preview(name, image)
    print("wrote the four icon sets and", len(images), "previews")

    if args.sheet:
        out = os.path.join(ROOT, "build", "icons")
        os.makedirs(out, exist_ok=True)
        sheet = Image.new("RGB", (5 * 360 + 60, 360 + 40), (241, 245, 250))
        for i, (name, image) in enumerate(images.items()):
            for size, radius, at in ((300, 68, (30, 20)), (60, 13, (0, 340)), (40, 9, (80, 350))):
                tile, mask = rounded(image, size, radius)
                sheet.paste(tile, (at[0] + i * 360, at[1]), mask)
        sheet.save(os.path.join(out, "sheet.png"))
        Image.fromarray(np.multiply(alpha, 255).astype(np.uint8)).save(os.path.join(out, "alpha.png"))
        print("wrote", os.path.join(out, "sheet.png"))


if __name__ == "__main__":
    sys.exit(main())
