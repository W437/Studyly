// `deno task bundle`: writes _shared/generated.ts from the files the functions read at run time, so a deployed
// function never depends on static-file support: the fixtures (raw text, so MOCK replies are byte-identical to the
// files the app bundles), the prompts, the JSON schemas and Apple's root certificates. tests/hygiene.test.ts fails
// when generated.ts is out of date.

const SHARED = new URL("./", import.meta.url);

async function listFiles(dir: URL, extension: string, prefix = ""): Promise<{ name: string; url: URL }[]> {
  const out: { name: string; url: URL }[] = [];
  for await (const entry of Deno.readDir(dir)) {
    if (entry.isDirectory) {
      out.push(...await listFiles(new URL(`${entry.name}/`, dir), extension, `${prefix}${entry.name}/`));
    } else if (entry.isFile && entry.name.endsWith(extension)) {
      out.push({ name: prefix + entry.name.slice(0, -extension.length), url: new URL(entry.name, dir) });
    }
  }
  return out.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

function base64(bytes: Uint8Array): string {
  let s = "";
  for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(s);
}

/** The text of generated.ts for the current sources. */
export async function renderGenerated(shared: URL = SHARED): Promise<string> {
  const fixtures: Record<string, string> = {};
  for (const f of await listFiles(new URL("fixtures/", shared), ".json")) {
    fixtures[f.name] = await Deno.readTextFile(f.url);
  }
  const prompts: Record<string, string> = {};
  for (const f of await listFiles(new URL("prompts/", shared), ".md")) {
    prompts[f.name] = (await Deno.readTextFile(f.url)).trim();
  }
  const contract = JSON.parse(await Deno.readTextFile(new URL("schemas/contract.json", shared)));
  const requests = JSON.parse(await Deno.readTextFile(new URL("schemas/requests.json", shared)));
  const roots: Record<string, string> = {};
  for (const f of await listFiles(new URL("apple/", shared), ".cer")) {
    roots[f.name] = base64(await Deno.readFile(f.url));
  }
  return [
    "// Generated by `deno task bundle` from _shared/fixtures, _shared/prompts, _shared/schemas and _shared/apple.",
    "// Do not edit by hand: edit the sources and run the task again.",
    "// deno-fmt-ignore-file",
    "// deno-lint-ignore-file",
    "",
    `export const FIXTURES: Record<string, string> = ${JSON.stringify(fixtures, null, 2)};`,
    "",
    `export const PROMPTS: Record<string, string> = ${JSON.stringify(prompts, null, 2)};`,
    "",
    `export const CONTRACT_SCHEMA: Record<string, any> = ${JSON.stringify(contract, null, 2)};`,
    "",
    `export const REQUEST_SCHEMA: Record<string, any> = ${JSON.stringify(requests, null, 2)};`,
    "",
    `export const APPLE_ROOTS: Record<string, string> = ${JSON.stringify(roots, null, 2)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  await Deno.writeTextFile(new URL("generated.ts", SHARED), await renderGenerated());
}
